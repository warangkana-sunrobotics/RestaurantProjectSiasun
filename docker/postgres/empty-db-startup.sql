-- ตารางออเดอร์ (ต้นทาง)
-- order_id ให้ฐานข้อมูลสร้างเอง (identity) เพื่อไม่ให้ชนกันเมื่อ API restart หรือมีหลาย worker
-- cost = ราคาต่อ 1 หน่วย, ยอดของแถว = cost * quantity, status: open = ยังไม่จ่าย / paid = เช็คบิลแล้ว
CREATE TABLE IF NOT EXISTS public.orders (
    order_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id   BIGINT        NOT NULL CHECK (table_id > 0),
    menu       VARCHAR(255)  NOT NULL CHECK (length(btrim(menu)) > 0),
    cost       NUMERIC(10,2) NOT NULL CHECK (cost >= 0),
    menu_id    INT           REFERENCES public.menu (menu_id),
    quantity   INT           NOT NULL DEFAULT 1 CHECK (quantity BETWEEN 1 AND 99),
    status     VARCHAR(10)   NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'paid')),
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    paid_at    TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_orders_table_status ON public.orders (table_id, status);

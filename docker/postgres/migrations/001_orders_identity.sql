-- ใช้เมื่อมี volume เดิมที่มีตาราง orders แบบเก่า (BIGINT/REAL ไม่มี identity) และไม่อยากลบข้อมูล
-- รันด้วย: docker exec -i daily-postgres psql -U <user> -d <db> < docker/postgres/migrations/001_orders_identity.sql
BEGIN;
ALTER TABLE public.orders ALTER COLUMN cost TYPE NUMERIC(10,2) USING cost::numeric(10,2);
ALTER TABLE public.orders ALTER COLUMN table_id SET NOT NULL;
ALTER TABLE public.orders ALTER COLUMN menu SET NOT NULL;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT now();
ALTER TABLE public.orders ALTER COLUMN order_id ADD GENERATED BY DEFAULT AS IDENTITY;
-- ตั้งตัวนับต่อจาก order_id สูงสุดที่มีอยู่
SELECT setval(pg_get_serial_sequence('public.orders', 'order_id'),
              COALESCE((SELECT MAX(order_id) FROM public.orders), 0) + 1, false);
CREATE INDEX IF NOT EXISTS idx_orders_table_id ON public.orders (table_id);
COMMIT;
